'''
3.	Всем известно, что из трех отрезков разной длины далеко не всегда можно составить треугольник, соединив их концы.
Напишите функцию для определения возможности построения треугольника на основании длин трех его потенциальных сторон.
Функция должна принимать три числовых параметра и возвращать булево значение.
Если длина хотя бы одной из трех сторон меньше или равна нулю, функция должна вернуть False.
В противном случае необходимо выполнить проверку на допустимость построения треугольника на
основании введенных длин сторон и вернуть соответствующее значение.
'''

a, b, c = map(int, input().split())

triangle_check = (
    a > 0 and
    b > 0 and
    c > 0 and
    a + b > c and
    b + c > a and
    c + a > b
)

print(triangle_check)